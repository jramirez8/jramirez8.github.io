function setLanguage(lang) {
  const safeLang = lang === 'es' ? 'es' : 'en';
  document.documentElement.lang = safeLang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const item = translations[el.dataset.i18n];
    if (item) el.textContent = item[safeLang];
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const item = richTranslations[el.dataset.i18nHtml];
    if (item) el.innerHTML = item[safeLang];
  });

  document.querySelectorAll('[data-lang-option]').forEach((el) => {
    el.classList.toggle('is-active', el.dataset.langOption === safeLang);
  });

  if (toggle) {
    toggle.setAttribute('aria-pressed', safeLang === 'es' ? 'true' : 'false');
    toggle.setAttribute('aria-label', safeLang === 'en' ? 'Cambiar sitio a español' : 'Switch site to English');
  }

  document.title = safeLang === 'en'
    ? 'Juan Ignacio Ramirez — IT Field Support Technician'
    : 'Juan Ignacio Ramirez — Técnico de Soporte IT de Campo';
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.content = safeLang === 'en'
    ? 'Juan Ignacio Ramirez — IT Field Support Technician. Networking, hardware, Windows environments, structured cabling, electronics repair and multi-site field support.'
    : 'Juan Ignacio Ramirez — Técnico de Soporte IT de Campo. Redes, hardware, entornos Windows, cableado estructurado, reparación electrónica y soporte multi-sitio.';

  localStorage.setItem('site-language', safeLang);
}

const savedLanguage = localStorage.getItem('site-language');
